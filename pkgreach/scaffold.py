"""Setting up a repository: the config and the weekly workflow.

``pkgreach init <dir> --pypi alice --npm alice`` writes ``pkgreach.toml`` and
``.github/workflows/pkgreach.yml``: every Sunday, the workflow collects into
the history (kept on the ``pkgreach-data`` branch of the same repository),
builds the report and publishes it on the repository's GitHub Pages.

Everything pkgreach collects is public already (download counts, dependents,
stars of public repositories), so the repository can be public, and needs no
secret: the workflow's own token reads GitHub and pushes the history.
"""

from __future__ import annotations

from collections.abc import Iterable, Mapping
from pathlib import Path

from pkgreach.platforms import PLATFORMS

ACTION_REPO = "thorwhalen/pkgreach"
FALLBACK_ACTION_REF = f"{ACTION_REPO}@main"
#: 05:23 UTC on Sundays: off the top of the hour (GitHub delays on-the-hour
#: crons). Registries keep 3 to 18 months of daily counts, so weekly runs lose
#: nothing even when a few are missed.
DFLT_CRON = "23 5 * * 0"
WORKFLOW_PATH = ".github/workflows/pkgreach.yml"
CONFIG_PATH = "pkgreach.toml"

WORKFLOW_TEMPLATE = """\
# Collects package stats every Sunday and publishes the report on GitHub Pages.
# Generated by `pkgreach init`. Docs: https://github.com/thorwhalen/pkgreach
#
# Needs no secret. The history is kept on the `pkgreach-data` branch.
# One-time setup: Settings -> Pages -> Source: "GitHub Actions".
name: pkgreach
on:
  schedule:
    - cron: "{cron}"
  workflow_dispatch:
permissions:
  contents: write
  pages: write
  id-token: write
concurrency:
  group: pkgreach
  cancel-in-progress: false
jobs:
  collect:
    runs-on: ubuntu-latest
    timeout-minutes: 30
    environment:
      name: github-pages
      url: ${{{{ steps.deploy.outputs.page_url }}}}
    steps:
      - uses: actions/checkout@v4
      - uses: {action_ref}
        id: reach
      - uses: actions/upload-pages-artifact@v3
        with:
          path: ${{{{ steps.reach.outputs.site-dir }}}}
      - uses: actions/deploy-pages@v4
        id: deploy
"""

CONFIG_HEADER = """\
# pkgreach settings: one table per platform. Every key is optional; see
# https://github.com/thorwhalen/pkgreach#configuration
#
#   users    = accounts whose packages are all followed
#   packages = packages followed by name, on top of the users' ones
#   exclude  = glob patterns of package names to drop
#   where    = metadata a package must match, e.g. {{ fork = false }}
"""


def default_action_ref() -> str:
    """``thorwhalen/pkgreach@<installed version>``, or ``@main`` from a checkout."""
    try:
        from importlib.metadata import version

        return f"{ACTION_REPO}@{version('pkgreach')}"
    except Exception:  # noqa: BLE001 - not installed: a source checkout
        return FALLBACK_ACTION_REF


def _toml_list(items: Iterable[str]) -> str:
    return "[" + ", ".join(f'"{i}"' for i in items) + "]"


def _toml_inline(d: Mapping) -> str:
    def v(x):
        return str(x).lower() if isinstance(x, bool) else f'"{x}"'

    return "{ " + ", ".join(f"{k} = {v(x)}" for k, x in d.items()) + " }"


def config_text(users: Mapping[str, Iterable[str]], *, platforms=None) -> str:
    """The ``pkgreach.toml`` following ``users`` per platform (each platform's
    ``default_where`` included)."""
    platforms = PLATFORMS if platforms is None else platforms
    tables = []
    for platform, names in users.items():
        lines = [f"[{platform}]", f"users = {_toml_list(names)}"]
        where = getattr(platforms.get(platform), "default_where", None)
        if where:
            lines.append(f"where = {_toml_inline(where)}")
        tables.append("\n".join(lines))
    return CONFIG_HEADER.format() + "\n" + "\n\n".join(tables) + "\n"


def init_repo(
    directory: str | Path,
    *,
    users: Mapping[str, Iterable[str]],
    cron: str = DFLT_CRON,
    action_ref: str | None = None,
    overwrite: bool = False,
) -> list[str]:
    """Write the config and the workflow; return the paths written."""
    if not users:
        raise ValueError("Name at least one account, e.g. --pypi you --npm you.")
    root = Path(directory)
    files = {
        CONFIG_PATH: config_text(users),
        WORKFLOW_PATH: WORKFLOW_TEMPLATE.format(
            cron=cron, action_ref=action_ref or default_action_ref()
        ),
    }
    written = []
    for rel, text in files.items():
        path = root / rel
        if path.exists() and not overwrite:
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        written.append(rel)
    return written
